  for (const label of labels) await expect(page.getByRole('checkbox', { name: label, exact: true })).toBeChecked()
  await expect(page.getByRole('status')).toHaveText(feedback!)
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '1')
  await page.getByRole('link', { name: '← Part 1로 돌아가기', exact: true }).click()
  await page.getByRole('link', { name: '← 홈', exact: true }).click()
  await page.goto('/parts/part-1')
  await page.getByRole('link', { name: '카드 특징 찾아내기 · 추가 연습', exact: true }).click()
  await page.getByRole('button', { name: '이어서 연습하기' }).click()
  await expect(page.getByRole('status')).toHaveText(feedback!)
  await page.getByRole('button', { name: '다음', exact: true }).click()
  for (let i = 1; i < 4; i++) {
    await page.getByRole('checkbox').first().check()
    await page.getByRole('button', { name: '정답 확인' }).click()
    await page.getByRole('button', { name: i === 3 ? '완료' : '다음', exact: true }).click()
  }
  await expect(page.getByRole('heading', { name: '추가 연습을 마쳤어요' })).toBeVisible()
  await page.locator('.practice-result summary').first().click()
  await expect(page.locator('.practice-result details').first().getByText(/^내 선택:/)).toContainText('포켓 페어')
  await expect(page.locator('.practice-result details').first().getByText(/^내 선택:/)).toContainText('수딧')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: test.info().outputPath('part1-practice-review.png'), fullPage: true })
  await page.getByRole('link', { name: '← Part 1로 돌아가기', exact: true }).click()
  await page.getByRole('link', { name: '카드 특징 찾아내기 · 추가 연습', exact: true }).click()
  await expect(page.getByRole('button', { name: '연습 시작', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: '추가 연습을 마쳤어요' })).toHaveCount(0)
