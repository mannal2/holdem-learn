test('Part 1 각 연습의 카드·포지션과 종합 여섯 문제를 표시한다', async ({ page }) => {
  for (const id of ['compare-hands', 'classify-strength', 'same-hand-different-position', 'starting-hand-challenge']) {
    await page.goto(`/practice/part-1/${id}`)
    await page.getByRole('button', { name: '연습 시작', exact: true }).click()
    await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuemax', id === 'starting-hand-challenge' ? '6' : '4')
    if (id === 'compare-hands') await expect(page.locator('.practice-hands .playing-card')).toHaveCount(4)
    if (id === 'classify-strength') await expect(page.getByRole('radio')).toHaveCount(2)
    if (id === 'same-hand-different-position') await expect(page.locator('[aria-current]')).toHaveCount(1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    if (id === 'starting-hand-challenge') {
      for (let i = 0; i < 6; i++) {
        const checkboxes = page.getByRole('checkbox')
        if (await checkboxes.count()) await checkboxes.first().check()
        else await page.getByRole('radio').first().check()
        await page.getByRole('button', { name: '정답 확인' }).click()
        await page.getByRole('button', { name: i === 5 ? '완료' : '다음', exact: true }).click()
      }
      await expect(page.getByRole('heading', { name: '종합 연습을 마쳤어요' })).toBeVisible()
    }
  }
})

