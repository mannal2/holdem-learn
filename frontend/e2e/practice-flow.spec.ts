test('회차 완료 후 다른 문제를 뽑고 레슨 진도는 바꾸지 않는다', async ({ page }) => {
  await page.goto('/practice/part-2/pair-types')
  const lessonBefore = await page.evaluate(() => localStorage.getItem('holdem-learning-progress'))
  await page.getByRole('button', { name: '연습 시작', exact: true }).click()
  const firstIds = await page.evaluate(() => JSON.parse(localStorage.getItem('holdem-practice-progress')!).sessions['pair-types'].questionIds as string[])
  for (let i = 0; i < 4; i++) {
    await page.getByRole('radio').first().check()
    await page.getByRole('button', { name: '정답 확인' }).click()
    await page.getByRole('button', { name: i === 3 ? '완료' : '다음', exact: true }).click()
  }
  await expect(page.getByRole('heading', { name: '추가 연습을 마쳤어요' })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('holdem-learning-progress'))).toBe(lessonBefore)
  await page.getByRole('button', { name: '새 문제로 연습하기' }).click()
  const nextIds = await page.evaluate(() => JSON.parse(localStorage.getItem('holdem-practice-progress')!).sessions['pair-types'].questionIds as string[])
  expect(nextIds.some(id => firstIds.includes(id))).toBe(false)
  await expect(page.getByRole('radio').first()).not.toBeChecked()
  await page.getByRole('link', { name: '← Part 2로 돌아가기', exact: true }).click()
  await page.getByRole('link', { name: '원 페어의 위치 구분하기 · 추가 연습', exact: true }).click()
  await page.getByRole('button', { name: '새 문제로 연습하기' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: '취소', exact: true }).click()
  const retainedIds = await page.evaluate(() => JSON.parse(localStorage.getItem('holdem-practice-progress')!).sessions['pair-types'].questionIds as string[])
  expect(retainedIds).toEqual(nextIds)
})

test('문제를 이동하면 카드와 문제 시작을 바로 볼 수 있다', async ({ page }) => {
  await page.goto('/practice/part-2/read-current-hand')
  await expect(page.locator('header').getByRole('button', { name: '연습 시작', exact: true })).toBeVisible()
  await expect(page.locator('.message-panel')).toHaveCount(0)
  await page.screenshot({ path: test.info().outputPath('practice-start.png'), fullPage: true })
  await page.getByRole('button', { name: '연습 시작', exact: true }).click()
  for (let i = 0; i < 2; i++) {
    await page.getByRole('radio').first().check()
    await page.getByRole('button', { name: '정답 확인' }).click()
    await page.getByRole('button', { name: '다음', exact: true }).click()
    await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', String(i + 2))
    await expect.poll(async () => (await page.locator('.learning-session').boundingBox())!.y).toBeGreaterThanOrEqual(0)
    await expect.poll(async () => (await page.locator('.learning-session').boundingBox())!.y).toBeLessThan(page.viewportSize()!.height)
    await expect.poll(async () => (await page.locator('.poker-table').boundingBox())!.y).toBeGreaterThanOrEqual(0)
    await expect.poll(async () => (await page.locator('.poker-table').boundingBox())!.y).toBeLessThan(page.viewportSize()!.height)
    await expect(page.getByRole('button', { name: '연습 잠시 나가기' })).toHaveCount(0)
  }
  await page.getByRole('button', { name: '이전', exact: true }).click()
  await expect(page.getByRole('progressbar')).toHaveAttribute('aria-valuenow', '2')
  await expect.poll(async () => (await page.locator('.poker-table').boundingBox())!.y).toBeGreaterThanOrEqual(0)
  await expect.poll(async () => (await page.locator('.poker-table').boundingBox())!.y).toBeLessThan(page.viewportSize()!.height)
  await page.screenshot({ path: test.info().outputPath('practice-next-question.png') })
})

